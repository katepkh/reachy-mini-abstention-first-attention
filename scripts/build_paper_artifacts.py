def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _stage2_row(stage2: dict[str, Any], policy: str, split: str) -> dict[str, Any]:
    rows = [row for row in stage2["summary"] if row["policy"] == policy and row["split"] == split]
    if len(rows) != 1:
        raise ValueError(f"Expected one Stage 2A row for {policy}/{split}; got {len(rows)}")
    return rows[0]


