def render_confirmation_design(data: dict[str, dict[str, Any]]) -> str:
    manifest = data["confirmation"]
    counts: dict[str, int] = {}
    roles: dict[str, str] = {}
    descriptions: dict[str, str] = {}
    for condition in manifest["conditions"]:
        condition_id = condition["id"]
        counts[condition_id] = sum(
            item["condition_id"] == condition_id for item in manifest["canonical_trials"]
        )
        roles[condition_id] = condition["role"]
        descriptions[condition_id] = condition["description"]
    lines = [
        "<!-- Generated by scripts/build_paper_artifacts.py; do not edit. -->",
        "",
        "| Frozen condition | Role | Trials | Purpose |",
        "|---|---|---:|---|",
    ]
    for condition in manifest["conditions"]:
        condition_id = condition["id"]
        lines.append(
            f"| `{condition_id}` | {roles[condition_id].replace('_', ' ')} | {counts[condition_id]} | {descriptions[condition_id]} |"
        )
    lines.extend(
        [
            "",
            f"Protocol fingerprint: `{manifest['fingerprint']}`. The 54 trials comprise 18 matching positives and 36 hard negatives across three rooms and three visible-person headings.",
            "",
        ]
    )
    return "\n".join(lines)


