def rendered_manifest(outputs: dict[Path, bytes]) -> bytes:
    payload = {
        "schema": "reachy-paper-artifact-manifest-v1",
        "generator": "scripts/build_paper_artifacts.py",
        "sources": [
            {"path": path.relative_to(ROOT).as_posix(), "sha256": sha256_file(path)}
            for path in SOURCE_FILES
        ],
        "outputs": [
            {
                "path": path.relative_to(ROOT).as_posix(),
                "bytes": len(content),
                "sha256": sha256_bytes(content),
            }
            for path, content in sorted(outputs.items(), key=lambda item: item[0].as_posix())
        ],
        "publication_files": [
            {"path": path.relative_to(ROOT).as_posix(), "sha256": sha256_file(path)}
            for path in PUBLICATION_FILES
        ],
        "boundaries": {
            "network_connections": 0,
            "robot_connections": 0,
            "media_capture": 0,
            "figures_are_svg": True,
        },
    }
    return (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode("utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        data = _inputs()
        outputs = rendered_outputs(data)
        manuscript = MANUSCRIPT.read_text(encoding="utf-8")
        missing_tables = [
            path.name
            for path, content in outputs.items()
            if path.suffix == ".md" and content.decode("utf-8").strip() not in manuscript
        ]
        if missing_tables:
            print(
                "FAIL: manuscript does not contain the generated version of: "
                + ", ".join(missing_tables),
                file=sys.stderr,
            )
            return 1
        manifest = rendered_manifest(outputs)
        sidecar = f"{sha256_bytes(manifest)}  {MANIFEST.name}\n".encode("utf-8")
        expected = {**outputs, MANIFEST: manifest, MANIFEST_SIDECAR: sidecar}
        if args.write:
            for path, content in expected.items():
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content)
                print(f"WROTE: {path.relative_to(ROOT)}")
            return 0
        stale = [
            path.relative_to(ROOT).as_posix()
            for path, content in expected.items()
            if not path.is_file() or path.read_bytes() != content
        ]
        if stale:
            print("FAIL: stale or missing paper artifacts:", file=sys.stderr)
            for path in stale:
                print(f"  {path}", file=sys.stderr)
            return 1
        print(f"PASS: {len(outputs)} manuscript tables/figures match verified evidence.")
        print("PASS: all generated tables are embedded verbatim in docs/MANUSCRIPT.md.")
        print(f"PASS: paper artifact manifest binds {len(SOURCE_FILES)} source artifacts.")
        return 0
    except (AssertionError, KeyError, OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
