#!/usr/bin/env python3
"""Render the public result summary from frozen machine-readable artifacts.

This is an offline reporting tool.  It verifies every manifest-listed source
file before rendering and never opens a network, camera, microphone, or robot
connection.  It does not rerun the historical acquisition or policy-search
programs; that remaining reproducibility boundary is stated in the report.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import verify_results


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "GENERATED_RESULTS.md"


def _row(result: dict, policy: str, split: str) -> dict:
    matches = [
        item
        for item in result["summary"]
        if item["policy"] == policy and item["split"] == split
    ]
    if len(matches) != 1:
        raise ValueError(f"Expected one {policy!r}/{split!r} result; found {len(matches)}")
    return matches[0]


def verify_sources() -> int:
    """Verify the complete source bundle before using any aggregate."""
    return sum(
        check()
        for check in (
            verify_results.verify_stage2a,
            verify_results.verify_stage3v,
            verify_results.verify_stage3p,
            verify_results.verify_stage4,
        )
    )


def render_report() -> str:
    stage2 = verify_results.load_json(
        verify_results.ANALYSIS / "stage2a_policy_tournament_v1.json"
    )
    recorded = _row(stage2, "Recorded Stage 2A", "evaluation")
    selected = _row(stage2, "3-hit safety consensus", "evaluation")
    stage3v = verify_results.load_json(
        verify_results.MANIFESTS / "stage3v_confirmation_result_v3_freeze.json"
    )
    stage3p = verify_results.load_json(
        verify_results.MANIFESTS
        / "stage3p_association_gated_cue_confirmation_result_v1_freeze.json"
    )
    stage4 = verify_results.load_json(
        verify_results.MANIFESTS
        / "stage4a_supervised_motion_pilot_v3_diagnostic_freeze.json"
    )

    v = stage3v["validated_state"]
    p = stage3p["validated_state"]
    m = stage4["validated_state"]
    source_count = verify_sources()
    v_gates = sum(bool(value) for value in v["gates"].values())
    p_gates = sum(bool(value) for value in p["gates"].values())

    lines = [
        "# Generated public result summary",
        "",
        "<!-- Generated by scripts/regenerate_public_results.py; do not edit by hand. -->",
        "",
        "This table is reconstructed from the committed frozen JSON artifacts after "
        f"SHA-256 verification of **{source_count}** manifest-listed evidence files.",
        "",
        "| Stage | Frozen public result |",
        "|---|---|",
        (
            "| Stage 2A retrospective evaluation | Recorded policy: "
            f"{recorded['matching_confirmed_rows']}/{recorded['matching_tracking_rows']} "
            "matching tracked rows and "
            f"{recorded['hard_negative_confirmed_rows']}/{recorded['hard_negative_tracking_rows']} "
            "hard-negative tracked rows confirmed. Development-selected 3-hit policy: "
            f"{selected['matching_confirmed_rows']}/{selected['matching_tracking_rows']} and "
            f"{selected['hard_negative_confirmed_rows']}/{selected['hard_negative_tracking_rows']}, "
            "respectively. |"
        ),
        (
            "| Stage 3V horizontal passive holdout | "
            f"{v['accepted_trials']} accepted trials from {v['all_csv_attempts']} attempts; "
            f"{v['positive_trials_with_move']}/12 positive trials proposed movement; "
            f"{v['hard_negative_would_move_rows']} hard-negative would-move rows; "
            f"{v['wrong_sign_moves']} wrong-sign moves; maximum target error "
            f"{v['maximum_target_error_deg']:.3f} degrees; {v_gates}/{len(v['gates'])} gates passed. |"
        ),
        (
            "| Stage 3P passive cue confirmation | "
            f"{p['accepted_trials']} accepted trials from {p['all_csv_attempts']} attempts "
            f"({p['superseded_attempts']} superseded); {p['transition_trials']} transition trials; "
            f"{p['fail_closed_controls']} fail-closed controls; "
            f"{p['control_gate_authorised_adjustments']} control-authorized adjustments; "
            f"{p_gates}/{len(p['gates'])} gates passed; {p['actuation_commands']} actuation commands. |"
        ),
        (
            "| Stage 4A V3 supervised mechanical pilot | **FAIL**; "
            f"{m['physical_motion_trials']} physical trial; "
            f"{m['total_head_only_commands']} head-only commands; measured motion "
            f"{m['robust_measured_motion_from_baseline_deg']:.3f} degrees; target error "
            f"{m['robust_target_to_requested_target_error_deg']:.3f} degrees; return error "
            f"{m['robust_return_to_baseline_error_deg']:.3f} degrees; thresholds weakened after outcome: "
            f"{'yes' if m['thresholds_weakened_after_outcome'] else 'no'}. |"
        ),
        "",
        "## Integrity anchors",
        "",
        f"- Stage 2A split fingerprint: `{stage2['manifest_fingerprint']}`",
        f"- Stage 3V freeze bundle: `{stage3v['bundle_sha256']}`",
        f"- Stage 3P cue freeze bundle: `{stage3p['bundle_sha256']}`",
        f"- Stage 4A diagnostic freeze bundle: `{stage4['bundle_sha256']}`",
        "",
        "## Reproducibility boundary",
        "",
        "This report regenerates the public headline table from frozen aggregate artifacts and "
        "verifies their listed source files. It does **not** rerun the original policy searches, "
        "reconstruct every analysis from raw acquisition data, reproduce deleted encrypted audit "
        "clips, or exercise live hardware. Those are separate and still-open reproducibility tasks.",
        "",
    ]
    return "\n".join(lines)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if the committed report is stale")
    mode.add_argument("--write", action="store_true", help="replace the committed generated report")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        rendered = render_report()
        if args.write:
            OUTPUT.write_text(rendered, encoding="utf-8")
            print(f"WROTE: {OUTPUT.relative_to(ROOT)}")
            return 0
        if args.check:
            existing = OUTPUT.read_text(encoding="utf-8")
            if existing != rendered:
                print(
                    "FAIL: docs/GENERATED_RESULTS.md is stale; run "
                    "python scripts/regenerate_public_results.py --write",
                    file=sys.stderr,
                )
                return 1
            print("PASS: generated public result summary matches frozen evidence.")
            return 0
        print(rendered, end="")
        return 0
    except (AssertionError, KeyError, OSError, ValueError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
